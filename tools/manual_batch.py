def _extract_ocr_answer(text: str) -> ManualSolution | None:
    """Pull embedded answers from OCR garbage (Жауабы:, Ответ:, x=…)."""
    patterns = [
        (r"Жауабы:\s*([^\n.]+)", 1),
        (r"Жауабы:\s*([^\n]+)", 1),
        (r"Ответ:\s*(\d+)", 1),
        (r"(?:^|\s)([xyу])=([-\d.,]+)", 2),
        (r"\bR=(\d+(?:[.,]\d+)?)", 1),
        (r"(\d+)×0\.16=(\d+(?:\.\d+)?)", 2),
        (r"=\s*(\d+(?:[.,]\d+)?)\s*(?:м|км|см|л|°)?\s*$", 1),
        (r"->\s*x=(\d+(?:[.,]\d+)?)", 1),
        (r"х=(\d+(?:[.,]\d+)?)\s*м", 1),
    ]
    for pat, groups in patterns:
        m = re.search(pat, text, re.I | re.M)
        if not m:
            continue
        if groups == 2 and len(m.groups()) == 2:
            if m.re.pattern.startswith(r"(\d+)×"):
                steps = f"OCR: {m.group(1)}×0,16={m.group(2)}."
                return steps, m.group(2).replace(".", ","), "Есептеу (OCR)", "Medium"
            var = m.group(1)
            ans = m.group(2).replace(".", ",")
            steps = f"OCR ішіндегі {var}={ans}."
        else:
            ans = m.group(1).strip().replace(".", ",")
            steps = f"OCR ішіндегі жауап: {ans}."
        if ans and ans != "—":
            return steps, ans, "Есептеу (OCR)", "Hard"
    return None


