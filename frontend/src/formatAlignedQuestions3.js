// Original SYNAQ practice tasks. School labels indicate format, not exam provenance.
const item = (id, school, subject, topic, difficulty, statement, options, answer, solution) => ({
  id: `synaq_fit3_${id}`, school, subject, topic, difficulty, statement,
  options, answer: String(answer), solution,
  source: 'SYNAQ original; format-aligned 2026',
});
const nis = (id, subject, topic, difficulty, statement, options, answer, solution) =>
  item(`nis_${id}`, 'НИШ', subject, topic, difficulty, statement, options, answer, solution);
const bil = (id, subject, topic, difficulty, statement, options, answer, solution) =>
  item(`bil_${id}`, 'БИЛ', subject, topic, difficulty, statement, options, answer, solution);
const rf = (id, topic, difficulty, statement, answer, solution) =>
  item(`rf_${id}`, 'РФМШ', 'math', topic, difficulty, statement, null, answer, solution);

