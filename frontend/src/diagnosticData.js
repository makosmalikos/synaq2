export const topicName = (topic, lang) => T[topic]?.[lang] || topic;

export function validateDiagnosticData() {
  const errors = [];
  for (const [grade, questions] of Object.entries(DIAGNOSTIC_QUESTIONS)) {
    if (questions.length < 10) errors.push(`${grade}: less than 10 questions`);
    const ids = new Set();
    const topicCounts = {};
    questions.forEach((item) => {
      if (ids.has(item.id)) errors.push(`${grade}: duplicate ${item.id}`);
      ids.add(item.id);
      if (!T[item.topic]) errors.push(`${item.id}: unknown topic`);
      topicCounts[item.topic] = (topicCounts[item.topic] || 0) + 1;
      if (!item.ru || !item.kk) errors.push(`${item.id}: missing translation`);
      if (item.options.length !== 4) errors.push(`${item.id}: expected 4 options`);
      if (!item.options.includes(item.answer)) errors.push(`${item.id}: answer is not in options`);
    });
    if (Object.keys(topicCounts).length !== 5) errors.push(`${grade}: expected 5 balanced topics`);
    Object.entries(topicCounts).forEach(([topic, count]) => {
      if (count !== 2) errors.push(`${grade}/${topic}: expected 2 questions, got ${count}`);
    });
  }
  return errors;
}
