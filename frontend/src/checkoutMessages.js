export function checkoutErrorMessage(code, lang = 'kk', status = 0) {
  const normalized = status === 401 || code === 'Қайта кіріңіз' ? 'login_required'
    : code === 'Төлем баптаулары толық емес' ? 'server_not_configured' : code;
  const copy = Object.hasOwn(messages, normalized) ? messages[normalized] : messages.checkout_unavailable;
  return copy[lang === 'ru' ? 0 : 1];
}

export const checkoutNeedsVerification = (code) => [
  'checkout_verification_required', 'checkout_payment_pending', 'checkout_network_error',
].includes(code);

export function isCheckoutDestination(value) {
  if (typeof value !== 'string' || value.length > 2048) return false;
  try {
    const url = new URL(value);
    return url.protocol === 'https:' && !url.username && !url.password && !url.port
      && ['checkout.dodopayments.com', 'test.checkout.dodopayments.com'].includes(url.hostname)
      && /^\/session\/cks_[a-zA-Z0-9_-]{1,160}$/.test(url.pathname);
  } catch { return false; }
}
