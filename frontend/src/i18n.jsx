const KEY = 'synaq_lang';
const LangCtx = createContext({ lang: 'kk', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem(KEY) || 'kk'; } catch { return 'kk'; }
  });

  const setLang = (l) => {
    setLangState(l);
    try { localStorage.setItem(KEY, l); } catch {}
    document.documentElement.lang = l;
  };

  useEffect(() => { document.documentElement.lang = lang; }, [lang]);

  const t = (key) => DICT[lang]?.[key] ?? DICT.kk[key] ?? key;
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);

// Переключатель ҚАЗ / РУС — ставится в шапку лендинга и на экран входа.
export function LangSwitch({ dark = false }) {
  const { lang, setLang } = useLang();
  const base = {
    border: 0, background: 'none', cursor: 'pointer', padding: '4px 8px',
    borderRadius: 8, font: "600 12px 'IBM Plex Mono',monospace", letterSpacing: '.08em',
  };
  const on = { ...base, background: dark ? 'rgba(255,255,255,.16)' : 'rgba(23,20,15,.08)', color: dark ? '#fff' : '#17140F' };
  const off = { ...base, color: dark ? 'rgba(255,255,255,.55)' : '#9A9384' };
  return (
    <div style={{ display: 'inline-flex', gap: 2, alignItems: 'center' }}>
      <button style={lang === 'kk' ? on : off} onClick={() => setLang('kk')}>ҚАЗ</button>
      <button style={lang === 'ru' ? on : off} onClick={() => setLang('ru')}>РУС</button>
    </div>
  );
}
