// Second editor-checked batch of original SYNAQ practice problems.
// The school labels describe the practice section, not the provenance of a past exam.
const q = (id, school, subject, topic, difficulty, statement, options, answer, solution) => ({
  id: `synaq_fit2_${id}`, school, subject, topic, difficulty,
  statement, options, answer: String(answer), solution,
  source: 'SYNAQ original; format-aligned 2026',
});
const nis = (id, subject, topic, difficulty, statement, options, answer, solution) =>
  q(`nis_${id}`, 'НИШ', subject, topic, difficulty, statement, options, answer, solution);
const bil = (id, subject, topic, difficulty, statement, options, answer, solution) =>
  q(`bil_${id}`, 'БИЛ', subject, topic, difficulty, statement, options, answer, solution);
const rf = (id, topic, difficulty, statement, answer, solution) =>
  q(`rf_${id}`, 'РФМШ', 'math', topic, difficulty, statement, null, answer, solution);
const comparison = (id, statement, answer, solution) => nis(
  id, 'kolzar', 'kolzar', 2,
  `${statement}\nА — первая величина больше; В — вторая величина больше; Тең — величины равны.`,
  ['А', 'В', 'Тең'], answer, solution,
);

