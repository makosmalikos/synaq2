function buildFromBank(variantTag, title, timeLimitMin) {
  const qs = questions
    .filter(q => q.variant === variantTag)
    .sort((a, b) => a.num - b.num)
    .map(q => ({ num: q.num, topic: q.topic, statement: q.statement, answer: q.answer, image: q.image || null, solution: q.solution }));
  return { id: `rfmsh2025_${variantTag}`, title, timeLimitMin, questions: qs };
}

