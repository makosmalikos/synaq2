OPTIONS = ['A', 'B', 'C', 'D', 'E']


def build_bilq():
    out = []
    for t in TASKS:
        q = {
            'id': f'bil_sets_{t["num"]:02d}',
            'school': 'БИЛ',
            'subject': 'math',
            'topic': 'sys',
            'source': SOURCE,
            'num': t['num'],
            'statement': t['statement'],
            'answer': t['answer'],
            'solution': t.get('solution', ''),
            'options': OPTIONS,
        }
        if t.get('image'):
            q['image'] = t['image']
        out.append(q)
    return out


def main():
    items = build_bilq()
    text = DATA_JS.read_text(encoding='utf-8')
    start = text.index('export const bilQ = ')
    end = text.index('export const ktlQ = ')
    new = 'export const bilQ = ' + json.dumps(items, ensure_ascii=False, indent=2) + ';\n\n'
    DATA_JS.write_text(text[:start] + new + text[end:], encoding='utf-8')
    print(f'Wrote {len(items)} BIL tasks to bilQ')


if __name__ == '__main__':
    main()
