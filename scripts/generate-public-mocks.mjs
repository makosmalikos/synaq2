import fs from 'node:fs';
import { POOL } from '../frontend/src/bank.js';

const specs = {
  'РФМШ': { minutes: 120, subjects: [[null, 30, 1]] },
  'НИШ': { minutes: 240, subjects: [['math', 40, 1], ['kolzar', 60, 1], ['science', 20, 1], ['eng', 20, 2], ['rus', 20, 2], ['kaz', 20, 2]] },
  'БИЛ': { minutes: 110, subjects: [['math', 40, 1], ['logic', 10, 1], ['reading', 10, 1]] },
};

const usable = (question) => question?.id && question?.statement && question.answer != null
  && !['', '-', '—'].includes(String(question.answer).trim())
  && (!question.options || (Array.isArray(question.options) && question.options.length >= 2
    && question.options.map(String).includes(String(question.answer))));

const output = {};
for (const [school, spec] of Object.entries(specs)) {
  const questions = [];
  for (const [subject, count, section] of spec.subjects) {
    const candidates = POOL.filter((question) => usable(question)
      && (school === 'БИЛ' ? ['БИЛ', 'КТЛ'].includes(question.school) : question.school === school)
      && (subject == null || question.subject === subject));
    if (candidates.length < count) throw new Error(`${school}/${subject}: ${candidates.length} < ${count}`);
    for (const question of candidates.slice(0, count)) {
      questions.push({
        id: `public-${school}-${question.id}`,
        topic: question.subject || question.topic || 'math',
        section,
        statement: question.statement,
        options: question.options || null,
        answer: String(question.answer),
        image: question.image || null,
      });
    }
  }
  output[school] = { minutes: spec.minutes, questions };
}

const destination = new URL('../frontend/src/publicMockData.generated.js', import.meta.url);
fs.writeFileSync(destination, `// Generated by scripts/generate-public-mocks.mjs. Do not edit manually.\nexport const PUBLIC_MOCKS = Object.freeze(${JSON.stringify(output)});\n`);
