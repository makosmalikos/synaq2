import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CURRICULUM } from '../frontend/src/curriculumData.js';

const target=new URL('../frontend/src/curriculumCatalog.generated.js',import.meta.url);
export function curriculumCatalogSource() {
 const catalog=Object.fromEntries(Object.entries(CURRICULUM).map(([grade,topics])=>[grade,topics.map(topic=>({
   key:topic.key,topicId:topic.topicId,moduleId:topic.moduleId,title:topic.title,
   grade:topic.grade,quarter:topic.quarter,hours:topic.hours,chapterCount:topic.lecture.length,
 }))]));
 return '// Generated by scripts/generate-curriculum-catalog.mjs --write.\n'
  +'// Navigation and progress only: no lesson text, exercises or answers.\n'
  +`export const CURRICULUM_CATALOG = ${JSON.stringify(catalog,null,2)};\n`;
}
export function checkCurriculumCatalog() {
 try{return fs.readFileSync(target,'utf8')===curriculumCatalogSource();}catch{return false;}
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 if(process.argv.includes('--write')){fs.writeFileSync(target,curriculumCatalogSource());console.log('Generated curriculum metadata.');}
 else if(process.argv.includes('--check')){if(!checkCurriculumCatalog()){console.error('Curriculum catalog is stale. Run node scripts/generate-curriculum-catalog.mjs --write');process.exitCode=1;}else console.log('Curriculum metadata matches all lesson IDs and reading steps.');}
 else process.stdout.write(curriculumCatalogSource());
}
