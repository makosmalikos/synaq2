import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { topics } from '../frontend/src/data.js';
import { POOL, EXTRA_TOPICS } from '../frontend/src/bank.js';
import { addQuestionsToTopics } from '../frontend/src/topicSummary.js';

const target = new URL('../frontend/src/topicCatalog.generated.js', import.meta.url);

export function topicCatalogSource() {
  return '// Generated by scripts/generate-topic-catalog.mjs --write. Do not edit by hand.\n'
    + '// Metadata only: no question statements, answers, explanations or images.\n'
    + `export const STATIC_TOPICS = ${JSON.stringify(addQuestionsToTopics([...topics, ...EXTRA_TOPICS], POOL), null, 2)};\n`
    + `export const STATIC_BANK_IDS = ${JSON.stringify(POOL.map((question) => question.id))};\n`;
}

export function checkTopicCatalog() {
  let actual;
  try { actual = fs.readFileSync(target, 'utf8'); } catch { return false; }
  return actual === topicCatalogSource();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (!checkTopicCatalog()) {
      console.error('Topic catalog is stale. Run: node scripts/generate-topic-catalog.mjs --write');
      process.exitCode = 1;
    } else console.log('Topic catalog matches the offline question bank.');
  } else if (process.argv.includes('--write')) {
    fs.writeFileSync(target, topicCatalogSource());
    console.log('Generated frontend/src/topicCatalog.generated.js');
  } else {
    process.stdout.write(topicCatalogSource());
  }
}
